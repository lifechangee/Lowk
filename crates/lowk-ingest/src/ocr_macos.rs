//! Apple Vision OCR (`VNRecognizeTextRequest`, accurate level, language correction on).
//! Images load through Vision's own URL handler (any ImageIO format incl. HEIC); PDF pages are
//! rasterised with CoreGraphics at about 2200 px on the long side (roughly 200-260 dpi for A4).
use crate::ocr::{languages_or_default, Ocr, OcrOutput};
use lowk_types::{AppError, ErrorCode, Result};
use objc2::rc::Retained;
use objc2::runtime::AnyObject;
use objc2::AllocAnyThread;
use objc2_core_foundation::{CFRetained, CFString, CFURLPathStyle, CGPoint, CGRect, CGSize, CFURL};
use objc2_core_graphics::{
    CGBitmapContextCreateImage, CGColorSpace, CGContext, CGImage, CGPDFBox, CGPDFDocument, CGPDFPage,
};
use objc2_foundation::{NSArray, NSDictionary, NSString, NSURL};
use objc2_vision::{
    VNImageOption, VNImageRequestHandler, VNRecognizeTextRequest, VNRecognizedTextObservation, VNRequest,
    VNRequestTextRecognitionLevel,
};
use std::ffi::c_void;
use std::path::Path;
use std::ptr::NonNull;

extern "C-unwind" {
    // Not generated by objc2-core-graphics.
    fn CGBitmapContextCreate(
        data: *mut c_void,
        width: usize,
        height: usize,
        bits_per_component: usize,
        bytes_per_row: usize,
        space: *const CGColorSpace,
        bitmap_info: u32,
    ) -> *mut CGContext;
}

/// kCGImageAlphaNoneSkipLast
const ALPHA_NONE_SKIP_LAST: u32 = 5;
const TARGET_LONG_SIDE: f64 = 2200.0;
const MAX_LONG_SIDE: f64 = 6000.0;

pub struct Vision;

fn ocr_err(detail: impl Into<String>) -> AppError {
    AppError::new(ErrorCode::OcrFailed).with_detail(detail)
}

fn request(languages: &[String]) -> Retained<VNRecognizeTextRequest> {
    let req = VNRecognizeTextRequest::new();
    req.setRecognitionLevel(VNRequestTextRecognitionLevel::Accurate);
    req.setUsesLanguageCorrection(true);
    let langs: Vec<Retained<NSString>> = languages_or_default(languages)
        .iter()
        .map(|l| NSString::from_str(l))
        .collect();
    req.setRecognitionLanguages(&NSArray::from_retained_slice(&langs));
    req
}

fn collect(req: &VNRecognizeTextRequest) -> OcrOutput {
    let mut obs: Vec<(f64, f64, String, f32)> = vec![];
    if let Some(results) = req.results() {
        for o in results.iter() {
            let o: &VNRecognizedTextObservation = &o;
            let cands = o.topCandidates(1);
            if let Some(c) = cands.firstObject() {
                // boundingBox: normalised, origin bottom-left
                let b = unsafe { o.boundingBox() };
                obs.push((
                    b.origin.y + b.size.height,
                    b.origin.x,
                    c.string().to_string(),
                    c.confidence(),
                ));
            }
        }
    }
    // top to bottom, then left to right; lines whose tops are within ~1% of the page share a row
    obs.sort_by(|a, b| {
        if (a.0 - b.0).abs() < 0.01 {
            a.1.partial_cmp(&b.1).unwrap_or(std::cmp::Ordering::Equal)
        } else {
            b.0.partial_cmp(&a.0).unwrap_or(std::cmp::Ordering::Equal)
        }
    });
    let n = obs.len();
    let conf = (n > 0).then(|| obs.iter().map(|o| o.3).sum::<f32>() / n as f32);
    let text = obs.into_iter().map(|o| o.2).collect::<Vec<_>>().join("\n");
    OcrOutput {
        text,
        confidence: conf,
    }
}

fn perform(handler: &VNImageRequestHandler, req: &VNRecognizeTextRequest) -> Result<()> {
    let r: &VNRequest = req;
    handler
        .performRequests_error(&NSArray::from_slice(&[r]))
        .map_err(|e| ocr_err(e.localizedDescription().to_string()))
}

fn no_options() -> Retained<NSDictionary<VNImageOption, AnyObject>> {
    NSDictionary::new()
}

impl Ocr for Vision {
    fn available(&self) -> bool {
        true
    }
    fn name(&self) -> &'static str {
        "vision"
    }

    fn recognize_image(&self, path: &Path, languages: &[String]) -> Result<OcrOutput> {
        let p = path.to_str().ok_or_else(|| ocr_err("path is not valid UTF-8"))?;
        // Vision raises an NSException on bad input; objc2 turns Rust panics into aborts only
        // across FFI, and `initWithURL` itself is lazy, so unreadable files surface in `perform`.
        let url = NSURL::fileURLWithPath(&NSString::from_str(p));
        let handler = unsafe {
            VNImageRequestHandler::initWithURL_options(VNImageRequestHandler::alloc(), &url, &no_options())
        };
        let req = request(languages);
        perform(&handler, &req)?;
        Ok(collect(&req))
    }

    fn recognize_pdf_page(&self, pdf: &Path, page_index: usize, languages: &[String]) -> Result<OcrOutput> {
        let image = render_pdf_page(pdf, page_index)?;
        let handler = unsafe {
            VNImageRequestHandler::initWithCGImage_options(
                VNImageRequestHandler::alloc(),
                &image,
                &no_options(),
            )
        };
        let req = request(languages);
        perform(&handler, &req)?;
        Ok(collect(&req))
    }
}

fn render_pdf_page(pdf: &Path, page_index: usize) -> Result<CFRetained<CGImage>> {
    let p = pdf.to_str().ok_or_else(|| ocr_err("path is not valid UTF-8"))?;
    let cf_path = CFString::from_str(p);
    let url = CFURL::with_file_system_path(None, Some(&cf_path), CFURLPathStyle::CFURLPOSIXPathStyle, false)
        .ok_or_else(|| ocr_err("could not build a file URL"))?;
    let doc =
        CGPDFDocument::with_url(Some(&url)).ok_or_else(|| ocr_err("CoreGraphics could not open the PDF"))?;
    if CGPDFDocument::is_encrypted(Some(&doc)) && !CGPDFDocument::is_unlocked(Some(&doc)) {
        return Err(AppError::new(ErrorCode::DocEncrypted));
    }
    // CGPDFDocument pages are 1-based
    let page: CFRetained<CGPDFPage> = CGPDFDocument::page(Some(&doc), page_index + 1)
        .ok_or_else(|| ocr_err(format!("page {} not found", page_index + 1)))?;
    let media = CGPDFPage::box_rect(Some(&page), CGPDFBox::CropBox);
    let (w, h) = (media.size.width.max(1.0), media.size.height.max(1.0));
    let long = w.max(h);
    let scale = (TARGET_LONG_SIDE / long).clamp(1.0, MAX_LONG_SIDE / long);
    let (pw, ph) = ((w * scale).ceil() as usize, (h * scale).ceil() as usize);
    let cs = CGColorSpace::new_device_rgb().ok_or_else(|| ocr_err("no colour space"))?;
    // SAFETY: data == NULL lets CoreGraphics own and free the pixel buffer; the size is bounded
    // above (MAX_LONG_SIDE); a NULL return is handled below.
    let ctx_ptr =
        unsafe { CGBitmapContextCreate(std::ptr::null_mut(), pw, ph, 8, 0, &*cs, ALPHA_NONE_SKIP_LAST) };
    let ctx_nn = NonNull::new(ctx_ptr).ok_or_else(|| ocr_err("could not create the bitmap context"))?;
    // SAFETY: CGBitmapContextCreate follows the CF "Create" rule: we own one retain.
    let ctx: CFRetained<CGContext> = unsafe { CFRetained::from_raw(ctx_nn) };
    CGContext::set_rgb_fill_color(Some(&ctx), 1.0, 1.0, 1.0, 1.0);
    CGContext::fill_rect(
        Some(&ctx),
        CGRect {
            origin: CGPoint { x: 0.0, y: 0.0 },
            size: CGSize {
                width: pw as f64,
                height: ph as f64,
            },
        },
    );
    let t = CGPDFPage::drawing_transform(
        Some(&page),
        CGPDFBox::CropBox,
        CGRect {
            origin: CGPoint { x: 0.0, y: 0.0 },
            size: CGSize {
                width: pw as f64,
                height: ph as f64,
            },
        },
        0,
        true,
    );
    CGContext::concat_ctm(Some(&ctx), t);
    CGContext::draw_pdf_page(Some(&ctx), Some(&page));
    CGBitmapContextCreateImage(Some(&ctx)).ok_or_else(|| ocr_err("could not make an image of the page"))
}
